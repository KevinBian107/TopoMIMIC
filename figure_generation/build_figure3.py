#!/usr/bin/env python3
"""Build paper/figures/figure3.png.

Figure 3 is the method-scatter "headline" panel: per-(family, coverage) box
distributions of negated internal consistency (panel A) and negated MMD
(panel B), so that up-and-right is the ideal corner. Generated by
`topo_mimic.analysis.feature_analysis.method_scatter` and copied into
the paper figures directory.
"""
from __future__ import annotations

import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from topo_mimic.analysis.feature_analysis.method_scatter import (  # noqa: E402
    build_method_scatter,
)

OUT_PATH = REPO / "paper/figures/figure3.png"


def main() -> None:
    src = build_method_scatter()
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, OUT_PATH)
    print(f"wrote {OUT_PATH}  (copied from {src})")


if __name__ == "__main__":
    main()
