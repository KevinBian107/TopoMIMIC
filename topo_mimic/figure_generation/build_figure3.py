#!/usr/bin/env python3
"""Build paper/figures/figure4.png (manuscript Figure 4: coverage-vs-quality).

This is the coverage-vs-quality small-multiples panel: per-(family,
coverage) box distributions of negated internal consistency (panel A)
and negated MMD (panel B), one row per family, so that up-and-right is
the ideal regime. Generated by
`topo_mimic.analysis.feature_analysis.coverage_quality_panels` and
copied into the paper figures directory.
"""
from __future__ import annotations

import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

from topo_mimic.analysis.feature_analysis.coverage_quality_panels import (  # noqa: E402
    build_coverage_quality_panels,
)

OUT_PATH = REPO / "paper/bian_NeurReps_2026/figures/figure4.png"


def main() -> None:
    src = build_coverage_quality_panels()
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, OUT_PATH)
    print(f"wrote {OUT_PATH}  (copied from {src})")


if __name__ == "__main__":
    main()
